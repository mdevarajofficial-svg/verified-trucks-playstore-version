object LocalizationManager {
  var currentLanguage by mutableStateOf(AppLanguage.ENGLISH)

  fun setLanguage(code: String) {
    val matched = AppLanguage.entries.find { it.code.equals(code, ignoreCase = true) }
    if (matched != null) {
      currentLanguage = matched
    }
  }

  fun getStrings(lang: AppLanguage = currentLanguage): AppStrings {
    return when (lang) {
      AppLanguage.ENGLISH -> EnglishStrings
      AppLanguage.KANNADA -> KannadaStrings
      AppLanguage.TELUGU -> TeluguStrings
      AppLanguage.TAMIL -> TamilStrings
      AppLanguage.HINDI -> HindiStrings
      AppLanguage.MALAYALAM -> MalayalamStrings
      AppLanguage.MARATHI -> MarathiStrings
    }
  }
}

typealias SupportedLanguage = AppLanguage

val LocalAppStrings = compositionLocalOf { EnglishStrings }
val LocalAppLocalization = LocalAppStrings
val LocalLocalizationManager = compositionLocalOf { LocalizationManager }

@Composable
fun AppLocalizationProvider(
  language: AppLanguage = LocalizationManager.currentLanguage,
  content: @Composable () -> Unit,
) {
  val strings = LocalizationManager.getStrings(language)
  CompositionLocalProvider(
    LocalAppStrings provides strings,
    LocalLocalizationManager provides LocalizationManager,
  ) {
    content()
  }
}
